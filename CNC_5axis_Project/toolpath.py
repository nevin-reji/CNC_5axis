"""CAM: the toolpath for finishing a dome with a ball-end tool, the collision
check, and G-code in and out.

The part is a dome (a cap of a sphere) standing on the table. A 5-axis machine
can keep the tool perpendicular to the curved surface everywhere, which a
3-axis machine cannot. The tool follows a spiral from the top of the dome
outwards; at every point the tool axis is the surface normal.
"""
import numpy as np

import kinematics as kin

# Part: sphere of radius R whose centre is H below the table top
R_SPHERE, H_CENTRE = 40.0, 15.0
BASE_R = np.sqrt(R_SPHERE ** 2 - H_CENTRE ** 2)          # 37.1 mm footprint radius
# The part is clamped off-centre, as real parts usually are. Then the linear axes
# must move to keep the tool on the part while the table turns (tool-centre-point control).
OFFSET = np.array([20.0, -10.0, 0.0])
# Tool: ball-end mill; the programmed point is the centre of the ball
BALL_R = 3.0
STICKOUT, HOLDER_R = 25.0, 12.0                          # holder starts 25 mm up the tool
SAFE_Z = 45.0


def surface_height(x, y):
    """Height of the part (or table, 0) at a table position (part coordinates)."""
    r2 = (x - OFFSET[0]) ** 2 + (y - OFFSET[1]) ** 2
    return np.where(r2 < BASE_R ** 2, np.sqrt(np.maximum(R_SPHERE ** 2 - r2, 0)) - H_CENTRE, 0.0)


def dome_spiral(phi_max_deg=60.0, turns=12, step=0.5):
    """Spiral over the dome. phi is the angle from the top of the dome, theta the
    angle around it. Returns ball-centre points P (N, 3) and tool axes U (N, 3)."""
    phi_max = np.radians(phi_max_deg)
    pts, phi = [], 0.0
    while phi <= phi_max:
        theta = 2 * np.pi * turns * phi / phi_max
        n = np.array([np.sin(phi) * np.cos(theta), np.sin(phi) * np.sin(theta), np.cos(phi)])
        pts.append(n)
        # advance phi so the step along the surface is about `step` mm
        ds_dphi = R_SPHERE * np.hypot(1, 2 * np.pi * turns / phi_max * np.sin(phi))
        phi += step / ds_dphi
    U = np.array(pts)
    S = U * R_SPHERE + [0, 0, -H_CENTRE] + OFFSET         # contact point on the surface
    P = S + BALL_R * U                                     # ball centre
    return P, U


def holder_clearance(p, u, n=16):
    """Smallest gap (mm) between the tool-holder rim and the part/table below it.
    Negative means the holder would hit something."""
    c = p + STICKOUT * u
    e1 = np.cross(u, [1, 0, 0] if abs(u[0]) < 0.9 else [0, 1, 0]); e1 /= np.linalg.norm(e1)
    e2 = np.cross(u, e1)
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    rim = c + HOLDER_R * (np.outer(np.cos(t), e1) + np.outer(np.sin(t), e2))
    return float(np.min(rim[:, 2] - surface_height(rim[:, 0], rim[:, 1])))


def to_joints(P, U):
    """Inverse kinematics for every point, keeping the joints continuous."""
    Q, prev = [], None
    for p, u in zip(P, U):
        prev = kin.inverse(p, u, prev)
        Q.append(prev)
    return np.array(Q)


def write_gcode(Q, seg_times, path):
    """G-code for a real 5-axis controller (e.g. LinuxCNC with trivial kinematics).
    G93 = inverse-time feed: F = 1 / (minutes for this move). The planner already
    knows how long each move must take, and inverse time is the standard way to
    give mixed linear + rotary moves a feed rate."""
    L = ["(5-axis dome finishing, ball-end R3, generated by toolpath.py)",
         "G21 G90 G94 (mm, absolute, feed per minute)",
         "G0 Z%.3f" % SAFE_Z,
         "G0 X%.3f Y%.3f A%.3f C%.3f" % (Q[0][0], Q[0][1], Q[0][3], Q[0][4]),
         "G1 Z%.3f F300" % Q[0][2],
         "G93 (inverse-time feed)"]
    for q, t in zip(Q[1:], seg_times):
        L.append("G1 X%.3f Y%.3f Z%.3f A%.3f C%.3f F%.2f" % (*q, 60.0 / t))
    L += ["G94", "G0 Z%.3f" % SAFE_Z, "M30"]
    open(path, "w").write("\n".join(L) + "\n")
    return len(L)


def read_gcode(path):
    """Read back the G1 moves made in G93 mode -> joints (N, 5) and move times (s)."""
    Q, T, q, inv = [], [], dict(X=0, Y=0, Z=0, A=0, C=0), False
    for line in open(path):
        line = line.split("(")[0].strip()
        if not line:
            continue
        words = {w[0]: float(w[1:]) for w in line.split() if w[0] in "XYZACFGM"}
        inv = True if "G93" in line else False if "G94" in line else inv
        q.update({k: v for k, v in words.items() if k in "XYZAC"})
        if line.startswith("G1") and inv:
            Q.append([q[a] for a in "XYZAC"]); T.append(60.0 / words["F"])
    return np.array(Q), np.array(T)
